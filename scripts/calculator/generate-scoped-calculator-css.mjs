import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import Module from 'node:module';
import jitiPkg from 'jiti';
import postcss from 'postcss';

const SRC = path.join(process.cwd(), 'src');
const resolveFilename = Module._resolveFilename;
Module._resolveFilename = function (request, ...rest) {
  if (typeof request === 'string' && request.startsWith('@/')) request = path.join(SRC, request.slice(2));
  return resolveFilename.call(this, request, ...rest);
};
const jiti = (jitiPkg.default || jitiPkg)(path.join(process.cwd(), 'noop.js'), { esmResolve: true });
const { CABIN_CALCULATOR_SSR_STYLES } = jiti('./src/lib/cabinCalculatorSSR.ts');

const root = postcss.parse(CABIN_CALCULATOR_SSR_STYLES);
root.walkRules((rule) => {
  let parent = rule.parent;
  while (parent) {
    if (parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
    parent = parent.parent;
  }
  rule.selectors = rule.selectors.map((selector) => (
    selector.startsWith('.cabin-calculator-ssr')
      ? selector
      : `.cabin-calculator-ssr ${selector}`
  ));
});

const banner = '/* Generated by scripts/calculator/generate-scoped-calculator-css.mjs. */\n';
const css = `${banner}${root.toString()}\n`;
const moduleSource = [
  '// Generated by scripts/calculator/generate-scoped-calculator-css.mjs.',
  `export const CABIN_CALCULATOR_SCOPED_STYLES = ${JSON.stringify(css)};`,
  '',
].join('\n');
await writeFile(path.join('src', 'lib', 'cabinCalculatorScopedStyles.generated.ts'), moduleSource);
console.log('wrote src/lib/cabinCalculatorScopedStyles.generated.ts');
